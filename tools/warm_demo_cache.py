"""WU-20 — warm the cache so the demo cannot need the network.

    python tools/warm_demo_cache.py                 # sweep + read + verdict
    python tools/warm_demo_cache.py --check         # verify a warm cache
    python tools/warm_demo_cache.py --performer perf_mira_vance

Runs the **real** pipeline once against the real services and writes every
answer to a cache on disk. Then `DEMO_MODE=true` replays it with zero external
calls.

Why bother: the video shoot cannot die on a rate limit at 1am the night before
submission. This is roughly an hour of work against that, and `--check` means
nobody has to *hope* the cache is warm — they can ask.

**Prefers WU-19's `FirestoreCache` and falls back to a local JSON file.** Use
the Firestore one for anything the deployed app must replay: Cloud Run cannot
read a JSON file on your laptop, so a locally-warmed cache does nothing for the
hosted demo. `--cache file` forces the local one, which is still useful for a
laptop dry-run or when Firestore is unreachable.

What is cached, and by which key:

| Client          | Key                                        |
|-----------------|--------------------------------------------|
| `parallel_search` | queries + locale + mode + settings, 6h TTL |
| `web_risk_check`  | the URL, 6h TTL                            |
| `fetch_page`      | URL + locale + size cap, 6h TTL            |
| `Triage`          | sha256(page text) + prompt_version, no TTL |

Verdicts are absent on purpose: hard rule 7, never cache a verdict. The
reconciler recomputes on read, which costs nothing.
"""

